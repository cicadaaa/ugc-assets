import math, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Circle, Polygon, FancyArrowPatch
fig, ax = plt.subplots(figsize=(8, 8), dpi=150)
ax.set_xlim(-1.5, 7); ax.set_ylim(-5, 3.5); ax.set_aspect("equal"); ax.axis("off")
ax.add_patch(Rectangle((-1.5, -5), 8.5, 5, color="#55595e"))
ax.add_patch(Rectangle((-1.5, 0), 8.5, 2.5, color="#d9d4cc"))
ax.add_patch(Rectangle((-1.5, 2.5), 8.5, 1.0, color="#a89f91"))
ax.plot([-1.5, 7], [0, 0], color="#999", lw=4)
for i in range(8):
    ax.add_patch(Rectangle((-0.3, -0.5 - i * 0.6), 6.3, 0.32, color="#f2f2f2"))
def rr(cx, cy, w, h, ang, **kw):
    a = math.radians(ang)
    ax.add_patch(Polygon([(cx + dx*math.cos(a) - dy*math.sin(a), cy + dx*math.sin(a) + dy*math.cos(a))
                          for dx, dy in [(-w/2, -h/2), (w/2, -h/2), (w/2, h/2), (-w/2, h/2)]], zorder=3, **kw))
rr(1.2, -1.25, 0.95, 2.3, 0, fc="#efe8da", ec="#6b604c", lw=2)
ax.add_patch(Rectangle((0.72, -2.4), 0.2, 2.3, fc="#cbbfa8", ec="#6b604c", zorder=3))
ax.add_patch(Circle((1.2, -3.0), 0.36, fc="#e2d6bf", ec="#6b604c", lw=2, zorder=3))
rr(4.2, -0.8, 1.9, 0.75, -30, fc="#d6b98c", ec="#6b4f2a", lw=2)
ax.add_patch(Rectangle((3.6, -0.82), 0.3, 0.44, fc="#c9cdd2", ec="#222", zorder=4))
ax.plot([3.6, 3.6], [-0.82, -0.38], color="#1f5fbf", lw=4, zorder=5)
ax.add_patch(FancyArrowPatch((3.55, -0.6), (2.3, -0.6), arrowstyle="-|>", mutation_scale=18, color="#1f5fbf", lw=2, zorder=5))
ax.add_patch(Circle((4.85, -1.2), 0.13, fc="#111", zorder=4))
ax.add_patch(Circle((5.4, -0.75), 0.28, fc="#a8743f", ec="#5a3b1e", zorder=3))
ax.add_patch(FancyArrowPatch((1.75, -1.25), (2.5, -1.25), arrowstyle="-|>", mutation_scale=16, color="#6b604c", lw=2, zorder=5))
t = dict(fontsize=10, zorder=6)
ax.text(5.3, 3.0, "BUILDING", **t); ax.text(5.3, 1.9, "SIDEWALK", **t); ax.text(6.3, -0.3, "CURB", color="w", **t)
ax.text(5.3, -4.6, "ROAD", color="w", **t)
ax.text(-1.4, -2.4, "ZEBRA\nCROSSING\n(across\nthe road)", color="w", fontsize=9)
ax.text(0.75, -1.3, "SOFA", rotation=90, fontsize=10, zorder=6, va="center")
ax.text(1.75, -1.75, "seat faces\nthe desk", fontsize=8, color="#111", zorder=6)
ax.text(1.65, -3.1, "TABLE", fontsize=9, color="w")
ax.text(4.1, -1.15, "DESK", rotation=-30, fontsize=10, zorder=6)
ax.text(1.95, -0.25, "LAPTOP SCREEN\nFACES THE SOFA", fontsize=8, color="#1f5fbf", weight="bold", zorder=6)
ax.text(5.0, -1.3, "lamp", fontsize=8, color="w"); ax.text(5.75, -0.8, "chair", fontsize=8, color="w")
ax.text(-1.4, 3.2, "TOP VIEW — set layout (fixed)", fontsize=12, weight="bold")
